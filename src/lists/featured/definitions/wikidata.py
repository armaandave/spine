"""Award history and collections from Wikidata, plus the Nobel Prize in Literature.

Award lists are unranked, newest first, with "<year>" or "<year> · tie" as each
entry's note. They re-sync weekly so a new winner lands soon after Wikidata (or the
supplement in ``static/supplements/wikidata.csv``) records it.
"""

from datetime import timedelta

from lists.featured.registry import FeaturedList, Guards

WEEKLY = timedelta(days=7)
MONTHLY = timedelta(days=30)


def award(key, name, media_type, position, awards, *, source_name, source_url, description, guards=None, **params):
    """Return an award-history definition."""
    return FeaturedList(
        key=key,
        name=name,
        media_types=(media_type,),
        kind="award",
        position=position,
        adapter="wikidata",
        params={"mode": "award", "awards": list(awards), **params},
        cadence=WEEKLY,
        source_name=source_name,
        source_url=source_url,
        description=description,
        is_ranked=False,
        guards=guards or Guards(min_resolve_rate=0.8),
    )


